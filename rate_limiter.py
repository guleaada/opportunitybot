"""
rate_limiter.py — provider-aware rate limiting for OpportunityBot.

Tracks:
    - requests per minute (RPM)
    - requests per day (RPD)
    - tokens per minute (TPM)
    - tokens per day (TPD)

The limiter is intentionally conservative. Provider limits can be overridden
through environment variables without changing code.

IMPORTANT
---------
This limiter only tracks requests made by the current process/scan. It cannot
see usage generated by other applications, API keys, or previous processes.

If the provider itself returns HTTP 429, the caller should still treat that
provider as rate-limited for the remainder of the scan.
"""

import os
import time
from collections import defaultdict, deque
from threading import Lock


__all__ = [
    "wait_for_quota",
    "seconds_until_available",
    "DailyQuotaExceeded",
    "snapshot",
    "register_provider",
    "known_providers",
    "record_usage",
    "LIMITS",
]


# ═══════════════════════════════════════════════════════════════════════════
# EXCEPTIONS
# ═══════════════════════════════════════════════════════════════════════════


class DailyQuotaExceeded(Exception):
    """Raised when a provider's daily request/token budget is exhausted."""


class TokenQuotaExceeded(Exception):
    """Reserved for future explicit token-quota handling."""


